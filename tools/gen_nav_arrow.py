#!/usr/bin/env python3
"""
Generate the navigation arrow images for the map view HUD (LVGL 8.1,
RGB565 + per-pixel alpha byte, LV_COLOR_16_SWAP 0).

Output: App/Utils/nav_arrow_img.c (const lv_img_dsc_t, 33x33 each)
  - nav_arrow_solid_img  green fill + dark inner outline + white halo
  - nav_arrow_gray_img   muted gray fill (last known position)

The arrow points UP (north); the widget rotates it by GPS course with
lv_img_set_angle(). Re-run this script to change shape or colors:

    python3 tools/gen_nav_arrow.py
"""

SIZE = 33
SS = 8  # supersampling grid per axis

# Arrow outline, centered on (0,0), pointing up: tip at -11, tail half
# width 9.5, concave notch at (0, 4.8). Fits a 33x33 box under rotation
# incl. the 2.6 px halo dilation (max radius ~15.7 < 16.5).
BASE = [(0.0, -11.0), (9.5, 9.0), (0.0, 4.8), (-9.5, 9.0)]

COL_FILL = (0x2E, 0xE0, 0x6B)   # app green (live fix, following)
COL_GRAY = (0x8F, 0xA1, 0xB3)   # muted (last known position)
COL_DARK = (0x0A, 0x0E, 0x14)   # chip dark
COL_WHITE = (0xFF, 0xFF, 0xFF)


def scaled(d):
    """Polygon dilated (d > 0) / eroded (d < 0) by d px about the origin."""
    pts = []
    for x, y in BASE:
        r = (x * x + y * y) ** 0.5
        f = (r + d) / r if r else 1.0
        pts.append((x * f, y * f))
    return pts


def inside(poly, px, py):
    """Even-odd point-in-polygon test."""
    hit = False
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        if (y1 > py) != (y2 > py):
            t = (py - y1) / (y2 - y1)
            if px < x1 + t * (x2 - x1):
                hit = not hit
    return hit


def render(polys, fill):
    """Nested polygons (outer..inner): band coverage composited per pixel,
    alpha = outermost coverage."""
    n = len(polys)
    img = []
    for j in range(SIZE):
        for i in range(SIZE):
            c = [0] * n
            for sy in range(SS):
                for sx in range(SS):
                    px = i + (sx + 0.5) / SS - SIZE // 2
                    py = j + (sy + 0.5) / SS - SIZE // 2
                    for k, poly in enumerate(polys):
                        if inside(poly, px, py):
                            c[k] += 1
            tot = c[0] / (SS * SS)
            if tot <= 0.0:
                img.append((0, 0, 0, 0))
                continue
            cols = [COL_WHITE, COL_DARK, fill]
            r = g = b = 0.0
            for k in range(n):
                band = c[k] - (c[k + 1] if k + 1 < n else 0)
                r += cols[k][0] * band
                g += cols[k][1] * band
                b += cols[k][2] * band
            img.append((round(r / (SS * SS) / tot), round(g / (SS * SS) / tot),
                        round(b / (SS * SS) / tot), round(255 * tot)))
    return img


def rgb565(rgb):
    r, g, b = rgb
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return v & 0xFF, v >> 8


def emit(f, name, img):
    data_name = name + "_data"
    f.write("static const uint8_t %s[] = {\n" % data_name)
    for j in range(SIZE):
        row = []
        for i in range(SIZE):
            r, g, b, a = img[j * SIZE + i]
            lo, hi = rgb565((r, g, b))
            row += [lo, hi, a]
            assert max(row) <= 0xFF, "byte overflow at %d,%d" % (i, j)
        f.write("    " + " ".join("0x%02X," % v for v in row) + "\n")
    f.write("};\n\n")
    f.write("const lv_img_dsc_t %s = {\n" % name)
    f.write("    .header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA,\n")
    f.write("    .header.always_zero = 0,\n")
    f.write("    .header.reserved = 0,\n")
    f.write("    .header.w = %d,\n" % SIZE)
    f.write("    .header.h = %d,\n" % SIZE)
    f.write("    .data_size = %d,\n" % (SIZE * SIZE * 3))
    f.write("    .data = %s,\n" % data_name)
    f.write("};\n\n")


def preview(name, img):
    print("--- %s ---" % name)
    ramp = " .:-=+*#%@"
    for j in range(SIZE):
        line = ""
        for i in range(SIZE):
            a = img[j * SIZE + i][3]
            line += ramp[min(a * len(ramp) // 256, len(ramp) - 1)]
        print(line)


def main():
    layers = [(scaled(2.6), COL_WHITE),   # white halo
              (scaled(1.1), COL_DARK),    # dark outline
              (BASE, None)]               # colored fill
    solid = render([p for p, _ in layers], COL_FILL)
    gray = render([p for p, _ in layers], COL_GRAY)

    out = "App/Utils/nav_arrow_img.c"
    with open(out, "w") as f:
        f.write("/*\n")
        f.write(" * nav_arrow_img.c - generated by tools/gen_nav_arrow.py.\n")
        f.write(" * Do not edit by hand: tweak the script and re-run it.\n")
        f.write(" *\n")
        f.write(" * 33x33 RGB565 + alpha byte per pixel (LV_COLOR_16_SWAP 0),\n")
        f.write(" * arrow pointing up, rotated by GPS course via lv_img_set_angle().\n")
        f.write(" */\n\n")
        f.write('#include "nav_arrow_img.h"\n\n')
        emit(f, "nav_arrow_solid_img", solid)
        emit(f, "nav_arrow_gray_img", gray)
    print("wrote %s" % out)
    preview("solid", solid)
    preview("gray", gray)


if __name__ == "__main__":
    main()
